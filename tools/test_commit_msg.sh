#!/bin/sh
# commit-msg hook: attribution forms rejected, ordinary messages pass.
HOOK="$(dirname "$0")/commit-msg"
t=$(mktemp); fail=0
check() { # expected-rc message
  printf '%s\n' "$2" > "$t"
  sh "$HOOK" "$t" >/dev/null 2>&1; rc=$?
  [ "$rc" -eq "$1" ] || { echo "FAIL ($rc != $1): $2"; fail=1; }
}
check 1 "feat: x

Co-Authored-By: X"
check 1 "feat: x

🤖 Generated with Tool"
check 1 "fix: y

generated by a tool"
check 0 "feat: add setup skill"
check 0 "docs: mention the Claude plugin"
rm -f "$t"
[ "$fail" -eq 0 ] && echo "ok"
exit "$fail"
